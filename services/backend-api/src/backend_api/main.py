"""SES Backend-API: internal API between the backend-services and the database.

Start:  uvicorn backend_api.main:app --host 0.0.0.0 --port 8001
Docs (auto generated by fastapi self):     http://localhost:8001/docs
"""

from contextlib import asynccontextmanager

import psycopg
from fastapi import FastAPI, Request
from fastapi.responses import JSONResponse

from .config import SERVICE_TOKENS
from .db import pool
from .routers import meterdata, reference, results


@asynccontextmanager
async def lifespan(app: FastAPI):
    missing = [name for name, token in SERVICE_TOKENS.items() if not token]
    if missing:
        raise RuntimeError(
            f"Service tokens missing for: {', '.join(missing)} "
            "(set SES_TOKEN_PROCESSING, SES_TOKEN_TRAINING, SES_TOKEN_FORECAST)"
        )
    pool.open()
    yield
    pool.close()


app = FastAPI(
    title="SES Backend API",
    description="Internal API for the Data processing service, the Ingest and training  "
    "pipeline and the Forecast pipeline.",
    version="1.0.0",
    lifespan=lifespan,
)

app.include_router(meterdata.router, prefix="/v1")
app.include_router(results.router, prefix="/v1")
app.include_router(reference.router, prefix="/v1")


@app.get("/health", tags=["status"])
def health():
    """Control for docker to check if the API is still running and if the database is reachable"""
    with pool.connection() as conn:
        conn.execute("SELECT 1")
    return {"status": "ok"}


# Database errors translation to HTTP-responses ----------


@app.exception_handler(psycopg.errors.InsufficientPrivilege)
def no_privilege(request: Request, exc: psycopg.Error):
    # the database refuses an action based on the role, which the API did let through
    return JSONResponse(
        status_code=403,
        content={"detail": "The database refuses the action for this service"},
    )


@app.exception_handler(psycopg.errors.UniqueViolation)
def duplicate(request: Request, exc: psycopg.Error):
    return JSONResponse(
        status_code=409,
        content={"detail": "Already exists", "constraint": exc.diag.constraint_name},
    )


@app.exception_handler(psycopg.errors.ForeignKeyViolation)
def missing_reference(request: Request, exc: psycopg.Error):
    return JSONResponse(
        status_code=422,
        content={
            "detail": "Item doesnt exist in the database",
            "constraint": exc.diag.constraint_name,
        },
    )


@app.exception_handler(psycopg.errors.CheckViolation)
def check_failed(request: Request, exc: psycopg.Error):
    # A check constraint in the database refuses the value
    return JSONResponse(
        status_code=422,
        content={
            "detail": "Value violates a check constraint in the database",
            "constraint": exc.diag.constraint_name,
        },
    )
